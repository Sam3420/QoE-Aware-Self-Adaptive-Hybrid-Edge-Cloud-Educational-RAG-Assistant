"""LQ (LLM response quality) for a learning session, read back from Langfuse evaluator scores.

Langfuse scores the `generate-answer` generations with an LLM-as-a-judge evaluator configured in the Langfuse UI
(docs/observability.md, "LQ from Langfuse"). At session end this module finds the session's generations, reads
their numeric scores named in LQ_SCORE_NAMES (on the generation or on its trace), normalises them to [0, 1]
and averages: first the score names per answer, then the answers.

Evaluators run asynchronously after ingestion, so the latest answers may not be scored yet: LQ covers the answers
scored so far (`scored`/`answers` say how many), and is None (unavailable) when nothing is scored, tracing is off
or Langfuse cannot be reached. It never raises: QoE is computed with or without it.
"""
import logging
import time
from collections import defaultdict
from typing import Any

from pydantic import BaseModel

from telemetry import tracing

logger = logging.getLogger(__name__)

GENERATION_NAME = "generate-answer"


class AnswerQuality(BaseModel):
    """LQ in [0, 1] (None = unavailable) and the evidence behind it."""

    value: float | None = None
    scored: int = 0  # answers with at least one evaluator score
    answers: int = 0  # answers generated by an LLM in this session (traced)
    reason: str = ""  # why value is None, or "" when measured


def session_answer_quality(session_id: str, *, names: list[str], score_min: float = 0.0, score_max: float = 1.0,
                           wait_s: float = 0.0, timeout_s: float = 3.0, client: Any = None) -> AnswerQuality:
    """Mean normalised evaluator score of this session's answers (see module docstring)."""
    client = client if client is not None else tracing.get_client()
    if client is None:
        return AnswerQuality(reason="Langfuse tracing is off")
    if not names:
        return AnswerQuality(reason="no LQ score names configured")
    if score_max <= score_min:
        return AnswerQuality(reason="LQ score range is empty (LQ_SCORE_MAX <= LQ_SCORE_MIN)")
    options = {"timeout_in_seconds": timeout_s}
    try:
        tracing.flush()  # send this session's last spans before looking them up
        deadline = time.monotonic() + max(wait_s, 0.0)
        while True:
            answers = _answer_traces(client, session_id, options)
            per_answer = _scores_by_answer(client, answers, names, options) if answers else {}
            all_scored = bool(answers) and len(per_answer) >= len(answers)
            if all_scored or time.monotonic() >= deadline:
                break
            time.sleep(min(1.0, max(deadline - time.monotonic(), 0.0)))  # evaluators still running
    except Exception as exc:  # unreachable server, auth, API change: LQ is simply unavailable
        logger.warning("LQ not read from Langfuse: %s", exc)
        return AnswerQuality(reason=f"Langfuse not reachable ({type(exc).__name__})")
    if not answers:
        return AnswerQuality(reason="no traced LLM answers in this session")
    if not per_answer:
        return AnswerQuality(answers=len(answers),
                             reason=f"no '{', '.join(names)}' evaluator scores yet")
    span = score_max - score_min
    means = [sum(min(max((v - score_min) / span, 0.0), 1.0) for v in values) / len(values)
             for values in per_answer.values()]
    return AnswerQuality(value=round(sum(means) / len(means), 6), scored=len(per_answer), answers=len(answers))


def _answer_traces(client: Any, session_id: str, options: dict[str, Any]) -> dict[str, set[str]]:
    """trace id → ids of its generate-answer generations, for this session."""
    out: dict[str, set[str]] = defaultdict(set)
    cursor = None
    for _ in range(10):  # 10 × 100 generations is far more than one session asks
        page = client.api.observations.get_many(session_id=session_id, name=GENERATION_NAME, type="GENERATION",
                                                fields="core", limit=100, cursor=cursor, request_options=options)
        for obs in page.data:
            out[obs.trace_id].add(obs.id)
        cursor = getattr(getattr(page, "meta", None), "cursor", None)
        if not cursor:
            break
    return dict(out)


def _scores_by_answer(client: Any, answers: dict[str, set[str]], names: list[str],
                      options: dict[str, Any]) -> dict[str, list[float]]:
    """trace id → numeric scores (one per score name, averaged if repeated) on its generation(s) or the trace."""
    found: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for trace_id, generation_ids in answers.items():
        for name in names:
            page = client.api.scores.get_many(trace_id=trace_id, name=name, data_type="NUMERIC", limit=100,
                                              request_options=options)
            for score in page.data:
                subject = getattr(score, "subject", None)
                kind, subject_id = getattr(subject, "kind", None), getattr(subject, "id", None)
                if (kind == "observation" and subject_id in generation_ids) or (kind == "trace" and
                                                                               subject_id == trace_id):
                    if isinstance(score.value, (int, float)):
                        found[trace_id][name].append(float(score.value))
    return {tid: [sum(v) / len(v) for v in by_name.values()] for tid, by_name in found.items() if by_name}
